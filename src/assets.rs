/// Icon for a database object kind ("table", "view", ...); `group` gives the stacked variant.
pub fn object_icon(kind: &str, group: bool) -> SharedString {
    format!("icons/tablex/{kind}{}.svg", if group { "s" } else { "" }).into()
}

pub struct Assets;

impl AssetSource for Assets {
    fn load(&self, path: &str) -> Result<Option<Cow<'static, [u8]>>> {
        if let Some((_, bytes)) = OWN.iter().find(|(p, _)| *p == path) {
            return Ok(Some(Cow::Borrowed(bytes)));
        }
        if let Some(bytes) = LucideExtras.load(path)? {
            return Ok(Some(bytes));
        }
        gpui_kit::assets::Assets.load(path)
    }

    fn list(&self, path: &str) -> Result<Vec<SharedString>> {
        let mut paths = gpui_kit::assets::Assets.list(path)?;
        paths.extend(LucideExtras.list(path)?);
        paths.extend(
            OWN.iter()
                .filter(|(p, _)| p.starts_with(path))
                .map(|(p, _)| (*p).into()),
        );
        paths.sort();
        paths.dedup();
        Ok(paths)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use gpui_kit::assets::IconName as Lucide;

    #[test]
    fn every_icon_we_use_resolves() {
        let lucide = [
            Lucide::Database,
            Lucide::Layers,
            Lucide::Folder,
            Lucide::FolderOpen,
            Lucide::PanelLeft,
            Lucide::PanelBottom,
            Lucide::Briefcase,
            // Grid header: key icons and the column type icons.
            Lucide::KeyRound,
            Lucide::Hash,
            Lucide::Type,
            Lucide::ToggleLeft,
            Lucide::CalendarClock,
            Lucide::Calendar,
            Lucide::Clock,
            Lucide::Braces,
            Lucide::Binary,
            Lucide::FingerprintPattern,
            Lucide::Network,
            Lucide::Brackets,
            Lucide::List,
            // Welcome tour.
            Lucide::Moon,
            Lucide::Sun,
            Lucide::Monitor,
            Lucide::Code,
            Lucide::Palette,
        ];
        let objects = crate::model::ObjectKind::ALL
            .into_iter()
            .map(|k| k.as_str())
            .flat_map(|k| [object_icon(k, false), object_icon(k, true)])
            .map(|p| p.to_string());
        let paths = lucide
            .iter()
            .map(|i| i.path().to_string())
            .chain([POSTGRES_ICON.into(), SQLITE_ICON.into()])
            .chain(objects);
        for path in paths {
            let bytes = Assets
                .load(&path)
                .unwrap()
                .unwrap_or_else(|| panic!("missing icon {path}"));
            assert!(bytes.starts_with(b"<svg"), "{path} is not an svg");
        }
    }
}
