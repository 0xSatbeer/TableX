macro_rules! own {
    ($path:literal) => {
        (
            concat!("icons/", $path),
            include_bytes!(concat!("../assets/icons/", $path)),
        )
    };
}

// Our own SVGs: brand marks from Simple Icons (CC0) plus object glyphs generated by
